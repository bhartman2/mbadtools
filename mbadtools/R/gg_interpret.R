#' gg_vip
#'
#' @param .data a data frame created by `vip::vi`, with column names c("Variable", "Importance")
#' @param ... arguments to pass to `ggplot2::geom_col`
#'
#' @returns a ggplot
#' @export
#' @importFrom stats reorder
#' @importFrom rlang .data
#' @importFrom dplyr slice

#' @import ggplot2
#'
#' @examples
#' mpg_fit = lm(mpg ~ ., data=mtcars)
#' gg_vip(vip::vi(mpg_fit))
#' 
gg_vip = function(.data, ...) {
  
  if ("Sign" %in% colnames(.data) ) sign = .data$Sign 
  else sign = "red"
  
  vip_graph = ggplot(.data, ...) +
    geom_col(aes(x=stats::reorder(.data$Variable, .data$Importance),
                 y=.data$Importance,
                 fill = sign), alpha=.3, color="black", ...) +
    scale_fill_discrete(palette=c("red","green")) +
    coord_flip() +
    labs(y="Importance", x="Variable",
         title="Variable Importance") +
    theme_bw()
  return(vip_graph)
}

#' gg_pdp
#' 
#' Plots partial dependence plot for a variable selected with `pdp`
#'
#' @param .data a `pdp` object with variable selected
#' @param ... additional arguments to pass to `geom_point()`
#'
#' @returns a ggplot
#' @export
#'
#' @examples
#' mpg_fit = lm(mpg ~ disp + hp, data=mtcars)
#' gg_pdp(pdp::partial(mpg_fit, pred.var="disp", train=mtcars,
#'             type="regression"))
#' 
gg_pdp = function (.data, ...) {
  
  df = .data %>% data.frame
  var = colnames(df)[1]
  
  pdfplot = ggplot(df, aes(x= !!rlang::ensym(var), y=.data$yhat)) +
    geom_point(...) +
    geom_smooth(method="loess",formula='y~x')+
    ggplot2::geom_rug() +
    labs(title = "Partial dependence plot",
         x=var,
         y="Predicted target") +
    ggplot2::theme_bw()
  
  return(pdfplot)
  
}

#' gg_pdp3D
#' 
#' Creates a 3D partial dependence plot from data created from a `tidyverse` model by `pdp`
#'
#' @param .data a `pdp` object with two variables selected
#'
#' @returns a ggplot object
#' @export
#'
#' @examples
#' \dontrun{
#' }
gg_pdp3D = function(.data) {
  
  df = .data %>% data.frame
  var1 = colnames(df)[1]
  var2 = colnames(df)[2]
  
  pdpplot3d = ggplot(df, aes(x= !!rlang::ensym(var1),
                             y= !!rlang::ensym(var2),
                             z=.data$yhat)
  ) +
    geom_contour() +
    geom_contour_filled() +
    labs(x=var1, 
         y=var2,
         z="Predicted target") +
    theme_bw()
  
  return(pdpplot3d)
}

#' rpart_unscale_object
#' 
#' Rescales the driver splits in an `rpart` object using means and sds of training data. 
#' Caution: the new object only has splits scaled that are used in the tree plot and rules.
#'
#' @param surr_model_object an `rpart` model object
#' @param train_data_p training data, with unscaled drivers
#'
#' @returns `rpart` object with splits index column rescaled 
#' @export
#'
#' @examples
#' \dontrun{
#' }
rpart_unscale_object = function(surr_model_object, train_data_p) {
  
  # unique variables used in tree
  unique_svars0 = stringr::str_unique(surr_model_object$frame$var)
  myvars0= unique_svars0[unique_svars0!="<leaf>"]
  myvars0
  # skim variables, means and sds
  msd0 = skimr::skim(train_data_p) %>% 
    dplyr::select(skim_variable, numeric.mean, numeric.sd) %>% 
    dplyr::filter(skim_variable %in% myvars0)
  # names of variables in splits object
  nm = names(surr_model_object$splits[,"index"])
  # match names with those in the means and sds
  nm_match = match(nm, msd0$skim_variable)
  # get means and sd vectors
  m = msd0$numeric.mean[nm_match]
  s = msd0$numeric.sd[nm_match]
  # get split z-scores
  idx = surr_model_object$splits[,"index"] 
  # compute original value from z-scores
  idx1 = m + s*idx
  #copy the old model object
  surr_model_object1 = surr_model_object
  # replace the splits for the variables that appear in the tree
  surr_model_object1$splits[,"index"] = m+s*idx
  
  # surr_model_object1$splits
  
  return(surr_model_object1)
  
}

#' vi_pre
#' 
#' Creates `vip:vi()` style data frame for a model of class `pre` Features
#' are sorted in descending order of importance. Models of this class are 
#' essentially linear so a sign is reported as well. 
#' The result can be plotted with `gg_vip`.
#'
#' @param model model generated by `pre::pre`
#' @param num_features number of features to retain; default 15
#'
#' @returns a data frame with `num_features` rows and several columns:
#'  * code, rule id; created by pre
#'  * Variable, character variable; shows the rule in English
#'  * Importance, numeric variable importance
#'  * coefficient, numeric; coefficient in linear (lasso) regression
#'  * sd, numeric; standard deviation of coefficient
#'  * Sign, factor; -1 or 1 depending on sign of coefficient
#' @export
#'
#' @examples
#' \dontrun{
#' }
vi_pre = function(model, num_features=15) {
  n=num_features
  vi = importance(model, plot=F)$baseimps %>% 
    rename(Variable=.data$description, 
      Importance=.data$imp, 
      code=.data$rule) %>% 
    mutate(Sign = factor(sign(.data$coefficient))) %>% 
    slice(1:num_features)
  return(data.frame(vi))
}

#' Kleinsrule
#' 
#' Implements Klein's rule of thumb for linear models using `lm` to detect multicollinearity.
#'
#'Klein's rule of thumb is to run auxiliary regressions with each driver variable against 
#'  all the others. Then compare these r-squareds to the full regression on all the drivers.
#'  The function builds a tibble to make this comparison easy.
#'
#' @param .data a dataframe with the target and drivers under study.
#' @param response response for the regression
#'
#' @returns a tibble with the r-squared values of the main and all auxiliary regressions
#' @export
#'
#' @examples
#' \dontrun{
#' data(longley, package="datasets")
#' # this data is known to be collinear
#' Kleinsrule(longley, response = "Employed")
#' }
#' 
Kleinsrule = function (.data, response) {
   
  drivers = names(.data %>% dplyr::select(-dplyr::all_of(response)))
  T = tibble::tibble()
  
  # base case - all drivers
  f = str_c(response, " ~ .")
  g = stats::lm(f, data=.data) %>% broom::glance() %>%
    dplyr::pull(.data$r.squared)
  s = ""
  t = tibble::as_tibble(list(formula=f, rsq = g, s=s))
  T = dplyr::bind_rows(T,t)
  
  for (q in drivers) {
    f = str_c(q, " ~ . - ", q)
    g = stats::lm(f, data = .data %>% dplyr::select(-response)) %>% 
      broom::glance() %>% 
      dplyr::pull(.data$r.squared)
    s = dplyr::case_when( g > T$rsq[1] ~ "*", .default="")
    t = tibble::as_tibble(list(formula=f, rsq = g, s=s))
    T = dplyr::bind_rows(T,t)
  }
  
  return(T)
}